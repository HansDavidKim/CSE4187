"""Condition initial session clocks on observed training-prefix histories.

Only START clocks are reused. Shopping actions and all future activity remain
generated by the fitted model. This is conditional initialization, not a draw
from the population's unconditional account-birth/survival process.
"""
from pathlib import Path
import hashlib
import json
import math

import pandas as pd

from simulate.v4.irl.source_contract import file_sha, source_profile_id


TYPE = "outertrain_observed_session_start_history"


def load_history_schedule(path, model, *, history_days, eligibility_days):
    path = Path(path).resolve()
    bank = json.loads(path.read_text())
    if bank.get("schema_version") != 1 or bank.get("type") != TYPE:
        raise ValueError("unsupported source history schedule")
    if model.get("population") is not None or model.get("summary_scope", {}).get("mode") != "train_only":
        raise ValueError("source history schedules require train-only source profiles")
    source = model["source"]
    domain = source.get("domain")
    prepared = source.get("prepared_source_cache", {})
    cutoff = pd.Timestamp(source.get("training_cutoff_at"))
    if cutoff.tzinfo is None:
        raise ValueError("history source cutoff must be timezone-aware")
    if (bank.get("domain") != domain or pd.Timestamp(bank.get("source_cutoff_at")) != cutoff
            or bank.get("prepared_source_sha256") != prepared.get("sha256")
            or file_sha(prepared["path"]) != prepared["sha256"]):
        raise ValueError("source history bank requires the exact fitted prepared source and cutoff")
    if bank.get("conditioning") != {"history_days": history_days, "recent_session_days": eligibility_days}:
        raise ValueError("source history eligibility differs from the requested experiment")
    profiles = {row["profile_id"]: index for index, row in enumerate(model["profiles"])}
    records = bank.get("records")
    if not isinstance(records, list) or not records:
        raise ValueError("source history bank has no supported training donors")
    seen = set()
    for row in records:
        uid = row.get("source_user_id")
        if (not isinstance(uid, str) or uid in seen
                or hashlib.sha256(f"42:{uid}".encode()).digest()[0] >= 205
                or row.get("profile_id") != source_profile_id(domain, uid)
                or row["profile_id"] not in profiles):
            raise ValueError("history donors must be unique fitted outer-training users")
        seen.add(uid)
        offsets = row.get("session_start_offsets_seconds")
        if (not isinstance(offsets, list) or not offsets
                or any(isinstance(x, bool) or not isinstance(x, (int, float)) or not math.isfinite(x) or x >= 0 for x in offsets)
                or offsets != sorted(offsets)
                or -offsets[0] < history_days * 86400
                or offsets[-1] < -eligibility_days * 86400):
            raise ValueError("history START clocks must be strict past and satisfy declared past eligibility")
    return bank


def draw_history_schedule(bank, rng, as_of, *, earliest):
    """Select one donor uniformly; never retry on a future or model outcome."""
    row = bank["records"][int(rng.integers(len(bank["records"])))]
    as_of, earliest = pd.Timestamp(as_of), pd.Timestamp(earliest)
    starts = [as_of + pd.Timedelta(seconds=x) for x in row["session_start_offsets_seconds"]]
    if starts[0] < earliest or starts[-1] >= as_of:
        raise ValueError("source history schedule exceeds available past observation")
    return row["profile_id"], starts


def history_provenance(path, bank):
    return {"type": TYPE, "path": str(Path(path).resolve()), "sha256": file_sha(path),
            "domain": bank["domain"], "source_cutoff_at": bank["source_cutoff_at"],
            "prepared_source_sha256": bank["prepared_source_sha256"], "donor_users": len(bank["records"]),
            "conditioning": bank["conditioning"], "source_users": "outertrain only; strict source-prefix session START clocks",
            "past_actions": "fresh fitted IRL draws, not copied source actions",
            "future": "unchanged fitted activity, timing and shopping; no outcome-conditioned donor selection",
            "scope": "conditional on observed source history timing; not unconditional signup/survival fidelity"}
